"""Rebuild tiny saddle-to-hoof occupancy masks; no game art or labels in the HUD.
Authoring only: python tools/bake_mattes.py (Pillow). No canvas readback in game.
"""
from pathlib import Path
from base64 import b64encode
from PIL import Image
from trot_stock import unroll
root=Path(__file__).resolve().parents[1]; rows=bytearray()
for file,w,h,cols,count in [('runner-1',132,105,14,336),('standing-1',308,245,6,6),('loading-walk',120,96,8,8),('flank-trot',308,245,6,24)]:
    alpha=Image.open(root/'assets'/(file+'.webp')).getchannel('A')
    if file=='runner-1':alpha=unroll(alpha,'turn')
    if file=='flank-trot':alpha=unroll(alpha.crop((0,0,w*cols,h*4)),'hd')
    assert alpha.width==w*cols and alpha.height>=((count+cols-1)//cols)*h,file
    for i in range(count):
        x=i%cols*w;y=i//cols*h
        pixels=alpha.crop((x,y,x+w,y+h)).resize((32,24),Image.Resampling.BOX).tobytes()
        for r in range(24):rows.extend(sum(int(a>42)<<j for j,a in enumerate(pixels[r*32:r*32+32])).to_bytes(4,'little'))
(root/'js/horse-mattes.js').write_text("/* Generated by tools/bake_mattes.py. 32×24 one-bit silhouettes, not pick targets. */\nglobalThis.AscotMattes=Uint8Array.from(atob('"+b64encode(rows).decode()+"'),c=>c.charCodeAt(0));\n")
